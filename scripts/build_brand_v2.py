#!/usr/bin/env python3
"""Build firmware-native assets from the pinned Core Brand V2 PNGs, offline."""
from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/brand-v2"
PRODUCER = "883cb9f3ff9de8ec7f5ae4c5f04f852e0d8bd866"
MANIFEST_SHA256 = "73cc408e10d88aa1fb8a1be2783b9c577aec398ce3dcd54c2f997ad1425984d2"


def header(name: str, data: bytes, size: int | None = None) -> bytes:
    text = "// Generated by scripts/build_brand_v2.py; do not edit.\n#pragma once\n#include <Arduino.h>\n\n"
    if size:
        text += f"static constexpr uint16_t {name}_WIDTH = {size};\n"
        text += f"static constexpr uint16_t {name}_HEIGHT = {size};\n"
    text += f"static constexpr uint32_t {name}_LEN = {len(data)};\n"
    text += f"static const uint8_t {name}[] PROGMEM = {{\n"
    text += "\n".join("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ","
                       for i in range(0, len(data), 16))
    return (text + "\n};\n").encode()


def encode(image: Image.Image) -> bytes:
    # Explicit PNG framing + stored DEFLATE blocks: stable across Pillow/zlib
    # versions and architectures. These small build assets require no decoder
    # or decompression allocation beyond the browser's normal PNG handling.
    import struct
    import zlib
    def chunk(kind: bytes, payload: bytes) -> bytes:
        return struct.pack(">I", len(payload)) + kind + payload + struct.pack(">I", zlib.crc32(kind + payload))
    rgba = image.convert("RGBA")
    pixels = rgba.tobytes()
    stride = rgba.width * 4
    rows = b"".join(b"\0" + pixels[y:y + stride] for y in range(0, len(pixels), stride))
    blocks = []
    for start in range(0, len(rows), 65535):
        block = rows[start:start + 65535]
        blocks.append(bytes([int(start + len(block) == len(rows))]) + struct.pack("<HH", len(block), len(block) ^ 65535) + block)
    stream = b"\x78\x01" + b"".join(blocks) + struct.pack(">I", zlib.adler32(rows))
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", rgba.width, rgba.height, 8, 6, 0, 0, 0)) + chunk(b"IDAT", stream) + chunk(b"IEND", b"")


def rgb565(image: Image.Image, light: bool = False) -> bytes:
    # The framebuffer is opaque black. Composite explicitly; never drop alpha
    # or treat dark artwork pixels as transparency.
    background = Image.new("RGBA", image.size, (255, 255, 255, 255) if light else (0, 0, 0, 255))
    pixels = Image.alpha_composite(background, image).convert("RGB")
    result = bytearray()
    for r, g, b in pixels.get_flattened_data():
        color = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        if light:
            color ^= 0xffff  # Existing light-mode panel inversion restores RGB.
        result.extend((color >> 8, color & 255))
    return bytes(result)


def outputs() -> dict[str, bytes]:
    raw = (SOURCE / "producer-manifest.json").read_bytes()
    if hashlib.sha256(raw).hexdigest() != MANIFEST_SHA256:
        raise ValueError("producer manifest differs from the pinned handoff")
    manifest = json.loads(raw)
    images = {}
    for size in (16, 32, 40, 256):
        name = f"mark-{size}.png"
        blob = (SOURCE / name).read_bytes()
        expected = manifest["files"][f"assets/djconnect/brand-v2/{name}"]
        if hashlib.sha256(blob).hexdigest() != expected["sha256"]:
            raise ValueError(f"producer asset changed: {name}")
        image = Image.open(io.BytesIO(blob)).convert("RGBA")
        if image.size != (size, size) or image.getpixel((0, 0))[3] != 0:
            raise ValueError(f"unexpected dimensions/alpha: {name}")
        images[size] = image
    # The device uses the owner's selected headset-only variant at every size.
    # Resize the full-resolution producer master, never upscale a micro icon.
    name = "headset-master.png"
    blob = (SOURCE / name).read_bytes()
    headset_metadata = manifest["files"][f"assets/djconnect/brand-v2/{name}"]
    if hashlib.sha256(blob).hexdigest() != headset_metadata["sha256"]:
        raise ValueError(f"producer asset changed: {name}")
    headset = Image.open(io.BytesIO(blob)).convert("RGBA")
    if headset.size != (headset_metadata["width"], headset_metadata["height"]) or headset.getpixel((0, 0))[3] != 0:
        raise ValueError(f"unexpected dimensions/alpha: {name}")
    result = {}
    for size in (64, 80, 96, 128, 160, 170):
        image = headset.resize((size, size), Image.Resampling.LANCZOS)
        result[f"assets/esp_display/djconnect_icon_{size}x{size}.png"] = encode(image)
        if size == 160:
            result["include/assets/DJConnectIcon160.h"] = header("DJCONNECT_ICON_160_RGB565", rgb565(image), size)
            result["include/assets/DJConnectIcon160.h"] += header("DJCONNECT_ICON_160_RGB565_LIGHT", rgb565(image, light=True), size)
    result["include/assets/DJConnectMicro40.h"] = header("DJCONNECT_MICRO_40_RGB565", rgb565(images[40]), 40)
    result["include/assets/DJConnectMicro40.h"] += header("DJCONNECT_MICRO_40_RGB565_LIGHT", rgb565(images[40], light=True), 40)
    web = images[256].resize((192, 192), Image.Resampling.LANCZOS)
    result["include/assets/djconnect_icon_192_png.h"] = header("DJCONNECT_ICON_192_PNG", encode(web))
    result["include/assets/djconnect_micro_32_png.h"] = header("DJCONNECT_MICRO_32_PNG", (SOURCE / "mark-32.png").read_bytes())
    # Embed the canonical 16/32/40 PNGs directly into ICO directory entries.
    # Pillow's ICO writer can choose different resizing inputs; avoid that.
    import struct
    blobs = [(SOURCE / f"mark-{size}.png").read_bytes() for size in (16, 32, 40)]
    offset = 6 + 16 * len(blobs)
    entries = []
    for size, blob in zip((16, 32, 40), blobs):
        entries.append(struct.pack("<BBBBHHII", size, size, 0, 0, 1, 32, len(blob), offset))
        offset += len(blob)
    ico = struct.pack("<HHH", 0, 1, len(blobs)) + b"".join(entries) + b"".join(blobs)
    result["include/assets/djconnect_favicon_ico.h"] = header("DJCONNECT_FAVICON_ICO", ico)
    web_manifest = {"name": "DJConnect", "short_name": "DJConnect",
                    "description": "Your music. Your DJ.", "start_url": "/",
                    "display": "standalone", "background_color": "#070812",
                    "theme_color": "#6f6bff", "icons": [{"src": "/icon-192.png?v=4",
                    "sizes": "192x192", "type": "image/png", "purpose": "any"}]}
    result["include/assets/djconnect_site_webmanifest.h"] = header("DJCONNECT_SITE_WEBMANIFEST", (json.dumps(web_manifest, indent=2) + "\n").encode())
    receipt = {"producer_commit": PRODUCER, "producer_manifest_sha256": MANIFEST_SHA256,
               "qualification": "PINNED_REVIEW_CANDIDATE_NOT_PRODUCER_ACCEPTANCE",
               "framebuffer_composite": "RGBA over black (dark) or white with panel-inversion compensation (light); RGB565 big-endian",
               "micro_max_size": 40,
               "display_variant": "headset-only-all-sizes",
               "display_master": {"file": "headset-master.png", "sha256": headset_metadata["sha256"]},
               "outputs": {name: hashlib.sha256(blob).hexdigest() for name, blob in sorted(result.items())}}
    result["assets/brand-v2/consumer-manifest.json"] = (json.dumps(receipt, indent=2, sort_keys=True) + "\n").encode()
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, blob in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_bytes() != blob:
                raise SystemExit(f"stale generated brand asset: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(blob)
    print("Brand V2 assets match pinned source" if args.check else "Brand V2 assets generated")


if __name__ == "__main__":
    main()
